from __future__ import annotations

from dataclasses import dataclass

from app.chat.intent import IntentCategory, IntentClassification


@dataclass(frozen=True)
class RoutingDecision:
    intent: IntentClassification
    use_memory: bool
    use_search: bool
    use_ollama: bool
    confidence: int
    reason: str


class RoutingEngine:
    """Choose the minimal backend components needed for a user request."""

    DIRECT_INTENTS = {
        IntentCategory.GREETING,
        IntentCategory.IDENTITY_QUESTION,
    }

    def decide(self, intent: IntentClassification) -> RoutingDecision:
        if intent.category in self.DIRECT_INTENTS:
            return RoutingDecision(
                intent=intent,
                use_memory=False,
                use_search=False,
                use_ollama=False,
                confidence=max(intent.confidence, 96),
                reason="direct deterministic assistant response",
            )

        if intent.requires_search:
            confidence = 72 if intent.confidence >= 85 else 55
            return RoutingDecision(
                intent=intent,
                use_memory=intent.requires_memory,
                use_search=True,
                use_ollama=True,
                confidence=confidence,
                reason="external or current knowledge required before generation",
            )

        if intent.requires_memory:
            return RoutingDecision(
                intent=intent,
                use_memory=True,
                use_search=False,
                use_ollama=True,
                confidence=82,
                reason="memory or conversation context required",
            )

        return RoutingDecision(
            intent=intent,
            use_memory=False,
            use_search=False,
            use_ollama=True,
            confidence=max(intent.confidence, 80),
            reason="stable answer can be generated by the local model",
        )
